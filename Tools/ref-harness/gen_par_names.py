#!/usr/bin/env python3
"""Emit a C table {name, value} for every enumerator of `enum ParamEnums` in the
upstream Parameters.h. Values are NOT computed here: the generated file refers to
the enumerators themselves, so the C compiler stays the single source of truth."""
import re, sys

src = open(sys.argv[1], newline='').read()
m = re.search(r'enum\s+ParamEnums\s*\{(.*?)\n\s*\}\s*;', src, re.S)
if not m:
    sys.exit("enum ParamEnums not found")
body = re.sub(r'/\*.*?\*/', '', m.group(1), flags=re.S)
body = re.sub(r'//[^\n]*', '', body)
names = []
for item in body.split(','):
    item = item.strip()
    if not item:
        continue
    mm = re.match(r'([A-Za-z_]\w*)', item)
    if mm and mm.group(1) not in names:
        names.append(mm.group(1))
with open(sys.argv[2], 'w') as out:
    out.write("/* generated by gen_par_names.py - do not edit */\n")
    for n in names:
        out.write('{ "%s", %s },\n' % (n, n))
